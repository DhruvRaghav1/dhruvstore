def setup():
    """Create fresh PostgreSQL tables; no old data is imported."""
    with connect() as db:
        db.execute("""CREATE TABLE IF NOT EXISTS products (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL, category TEXT NOT NULL, price DOUBLE PRECISION NOT NULL,
            old_price DOUBLE PRECISION DEFAULT 0, stock INTEGER DEFAULT 0, image TEXT DEFAULT '',
            size_value DOUBLE PRECISION DEFAULT 1, size_unit TEXT DEFAULT 'piece'
        )""")
        db.execute("""CREATE TABLE IF NOT EXISTS orders (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            phone TEXT NOT NULL, items TEXT NOT NULL, total DOUBLE PRECISION NOT NULL,
            customer_name TEXT DEFAULT '', house TEXT DEFAULT '', area TEXT DEFAULT '',
            landmark TEXT DEFAULT '', city TEXT DEFAULT '', pincode TEXT DEFAULT ''
        )""")


def pretty_size(value):
    try:
        number = float(value)
        return str(int(number)) if number.is_integer() else str(number)
    except (TypeError, ValueError):
        return str(value)

app.jinja_env.filters["pretty_size"] = pretty_size


def cart_data():
    cart = []
    total = 0
    with connect() as db:
        for pid, qty in session.get("cart", {}).items():
            p = db.execute("SELECT * FROM products WHERE id=%s", (int(pid),)).fetchone()
            if p:
                item = dict(p)
                item["qty"] = qty
                cart.append(item)
                total += p["price"] * qty
    return cart, total


@app.context_processor
def inject_year():
    from datetime import datetime
    return {"year": datetime.now().year}


@app.route("/")
def home():
    with connect() as db:
        products = db.execute("SELECT * FROM products ORDER BY id DESC").fetchall()
    cart, total = cart_data()
    cart_count = sum(item["qty"] for item in cart)
    return render_template_string(PAGE, products=products, cart=cart, total=total, cart_count=cart_count)


@app.route("/add/<int:pid>", methods=["POST"])
def add(pid):
    try:
        qty = max(1, int(request.form.get("qty", 1)))
    except (ValueError, TypeError):
        qty = 1
    with connect() as db:
        product = db.execute("SELECT stock FROM products WHERE id=%s", (pid,)).fetchone()
    if not product or product["stock"] < qty:
        return "Sorry, that quantity is not available. Please go back and try again.", 400
    cart = session.get("cart", {})
    cart[str(pid)] = cart.get(str(pid), 0) + qty
    session["cart"] = cart
    return redirect(url_for("home", _anchor="cart"))


@app.route("/cart/update/<int:pid>", methods=["POST"])
def update_cart(pid):
    cart = session.get("cart", {})
    key = str(pid)
    if key not in cart:
        return redirect(url_for("home", _anchor="cart"))
    action = request.form.get("action")
    if action == "remove":
        cart.pop(key, None)
    elif action == "minus":
        cart[key] -= 1
        if cart[key] <= 0:
            cart.pop(key, None)
    elif action == "plus":
        with connect() as db:
            product = db.execute("SELECT stock FROM products WHERE id=%s", (pid,)).fetchone()
        if product and cart[key] < product["stock"]:
            cart[key] += 1
    session["cart"] = cart
    return redirect(url_for("home", _anchor="cart"))


@app.route("/order", methods=["POST"])
def order():
    customer_name = request.form.get("customer_name", "").strip()
    phone = request.form.get("phone", "").strip()
    house = request.form.get("house", "").strip()
    area = request.form.get("area", "").strip()
    landmark = request.form.get("landmark", "").strip()
    city = request.form.get("city", "").strip()
    pincode = request.form.get("pincode", "").strip()
    if not customer_name or len(customer_name) > 100:
        return "Please enter your full name.", 400
    if not phone.isdigit() or len(phone) != 10:
        return "Enter a valid 10-digit mobile number.", 400
    if not house or not area or not city:
        return "Please complete your delivery address.", 400
    if not pincode.isdigit() or len(pincode) != 6:
        return "Enter a valid 6-digit PIN code.", 400
    cart, total = cart_data()
    if not cart:
        return redirect(url_for("home"))
    lines = []
    with connect() as db:
        # Lock/check stock and write the order in one transaction.
        for item in cart:
            current = db.execute("SELECT stock FROM products WHERE id=%s FOR UPDATE", (item["id"],)).fetchone()
            if not current or current["stock"] < item["qty"]:
                return "Sorry, stock is insufficient. Please return to the store.", 400
            lines.append(f'{item["name"]} ({pretty_size(item["size_value"])} {item["size_unit"]}) x {item["qty"]}')
        for item in cart:
            db.execute("UPDATE products SET stock=stock-%s WHERE id=%s", (item["qty"], item["id"]))
        row = db.execute("""INSERT INTO orders
            (phone,items,total,customer_name,house,area,landmark,city,pincode)
            VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id""",
            (phone, ", ".join(lines), total, customer_name, house, area, landmark, city, pincode)).fetchone()
        order_id = row["id"]
    token = os.getenv("BOT_TOKEN")
    chat_id = os.getenv("CHAT_ID")
    if token and chat_id:
        address = f"{house}, {area}"
        if landmark:
            address += f", Near {landmark}"
        address += f", {city} - {pincode}"
        message = (f"🛒 NEW COD ORDER #{order_id}\nName: {customer_name}\nPhone: {phone}\nAddress: {address}\nProducts: {', '.join(lines)}\nTotal: ₹{total:.2f}\nPayment: Cash on Delivery")
        try:
            requests.post(f"https://api.telegram.org/bot{token}/sendMessage", data={"chat_id": chat_id, "text": message}, timeout=10)
        except requests.RequestException:
            pass
    session["cart"] = {}
    return (f"<main style='font-family:Arial;max-width:600px;margin:60px auto;padding:24px'>"
            f"<h1>✅ Order #{order_id} placed!</h1><p>Thank you for shopping at Dhruv Store.</p>"
            "<p>Your order is Cash on Delivery.</p><a href='/'>Continue shopping</a></main>")


